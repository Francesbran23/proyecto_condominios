CREATE TABLE IF NOT EXISTS administrador (
  id_administrador integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_administrador varchar(30) NOT NULL,
  apellido_paterno_administrador varchar(30) NOT NULL,
  apellido_materno_administrador varchar(30) NOT NULL,
  correo_administrador varchar(45) NOT NULL,
  contraseña_administrador varchar(255) NOT NULL,
  CONSTRAINT uq_administrador_correo UNIQUE (correo_administrador),
  CONSTRAINT chk_administrador_correo CHECK (
    correo_administrador = btrim(correo_administrador)
    AND correo_administrador ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'
  ),
  CONSTRAINT chk_administrador_contrasena_longitud CHECK (char_length(contraseña_administrador) >= 8),
  CONSTRAINT chk_administrador_nombre CHECK (char_length(btrim(nombre_administrador)) > 0)
);

CREATE TABLE IF NOT EXISTS "adeudos anteriores" (
  id_adeudos integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_adeudos double precision NOT NULL,
  descripcion_adeudos varchar(45) NOT NULL,
  CONSTRAINT chk_adeudos_monto_no_negativo CHECK (monto_adeudos >= 0)
);

CREATE TABLE IF NOT EXISTS "concepto de pago" (
  id_concepto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion_concepto varchar(45) NOT NULL
);

CREATE TABLE IF NOT EXISTS condominio (
  id_condominio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_condominio varchar(45) NOT NULL,
  direccion_condominio varchar(100) NOT NULL,
  CONSTRAINT uq_condominio_nombre UNIQUE (nombre_condominio)
);

CREATE TABLE IF NOT EXISTS "cuota de fondo de reserva" (
  id_reserva integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_reserva double precision NOT NULL,
  descripcion_reserva varchar(45) NOT NULL,
  CONSTRAINT chk_reserva_monto_no_negativo CHECK (monto_reserva >= 0)
);

CREATE TABLE IF NOT EXISTS "cuota de penalización" (
  id_penalizacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_penalizacion double precision NOT NULL,
  descripcion_penalizacion varchar(45) NOT NULL DEFAULT '',
  CONSTRAINT chk_penalizacion_monto_no_negativo CHECK (monto_penalizacion >= 0)
);

CREATE TABLE IF NOT EXISTS "cuota extraordinaria" (
  id_extraordinaria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_extraordinaria double precision NOT NULL,
  descrpicion_extraordinaria varchar(45) NOT NULL,
  CONSTRAINT chk_extraordinaria_monto_no_negativo CHECK (monto_extraordinaria >= 0)
);

CREATE TABLE IF NOT EXISTS "cuota ordinaria" (
  id_ordinaria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_ordinaria double precision NOT NULL,
  descripcion_ordinaria varchar(45) NOT NULL DEFAULT '',
  CONSTRAINT chk_ordinaria_monto_no_negativo CHECK (monto_ordinaria >= 0)
);

CREATE TABLE IF NOT EXISTS "direccion condominio" (
  id_direccion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_exterior_direccion integer NOT NULL,
  calle_direccion varchar(45) NOT NULL,
  colonia_direccion varchar(45) NOT NULL,
  delegacion_direccion varchar(45) NOT NULL,
  cp_direccion integer NOT NULL,
  ciudad_direccion varchar(45) NOT NULL,
  estado_direccion varchar(45) NOT NULL
);

CREATE TABLE IF NOT EXISTS "fecha de pago" (
  id_fecha integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia_fecha integer NOT NULL,
  mes_fecha varchar(15) NOT NULL,
  año_fecha integer NOT NULL
);

CREATE TABLE IF NOT EXISTS edificio (
  id_edificio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_condominio integer NOT NULL,
  nombre_edificio varchar(20) NOT NULL,
  CONSTRAINT uq_edificio_condominio_nombre UNIQUE (id_condominio, nombre_edificio),
  CONSTRAINT id_condominio FOREIGN KEY (id_condominio)
    REFERENCES condominio (id_condominio) ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS departamento (
  id_departamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_edificio integer NOT NULL,
  numero_departamento varchar(10) NOT NULL,
  CONSTRAINT uq_departamento_edificio_numero UNIQUE (id_edificio, numero_departamento),
  CONSTRAINT id_edificio FOREIGN KEY (id_edificio)
    REFERENCES edificio (id_edificio) ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS inquilino (
  id_inquilino integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_departamento integer,
  nombre_inquilino varchar(45) NOT NULL,
  apellino_paterno_inquilino varchar(45) NOT NULL,
  apellino_materno_inquilino varchar(45) NOT NULL,
  correo_inquilino varchar(45) NOT NULL,
  CONSTRAINT uq_inquilino_departamento_identidad UNIQUE (
    id_departamento, nombre_inquilino, apellino_paterno_inquilino,
    apellino_materno_inquilino, correo_inquilino
  ),
  CONSTRAINT chk_inquilino_correo CHECK (
    correo_inquilino = btrim(correo_inquilino)
    AND correo_inquilino ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'
  ),
  CONSTRAINT id_departamento FOREIGN KEY (id_departamento)
    REFERENCES departamento (id_departamento) ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS "total pagado" (
  id_total integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ordinaria integer NOT NULL REFERENCES "cuota ordinaria" (id_ordinaria) ON UPDATE CASCADE,
  id_extraordinaria integer NOT NULL REFERENCES "cuota extraordinaria" (id_extraordinaria) ON UPDATE CASCADE,
  id_penalizacion integer NOT NULL REFERENCES "cuota de penalización" (id_penalizacion) ON UPDATE CASCADE,
  id_reserva integer NOT NULL REFERENCES "cuota de fondo de reserva" (id_reserva) ON UPDATE CASCADE,
  id_adeudos integer NOT NULL REFERENCES "adeudos anteriores" (id_adeudos) ON UPDATE CASCADE,
  monto_total double precision NOT NULL,
  CONSTRAINT chk_total_monto_no_negativo CHECK (monto_total >= 0)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id_administrador integer PRIMARY KEY REFERENCES administrador (id_administrador) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_password_reset_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS recibo (
  id_recibo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no_recibo varchar(20) NOT NULL,
  id_condominio integer NOT NULL REFERENCES condominio (id_condominio) ON UPDATE CASCADE,
  id_departamento integer NOT NULL REFERENCES departamento (id_departamento) ON UPDATE CASCADE,
  id_inquilino integer NOT NULL REFERENCES inquilino (id_inquilino) ON UPDATE CASCADE,
  fecha date NOT NULL,
  estado_pago varchar(10) NOT NULL DEFAULT 'pendiente',
  fecha_pago timestamptz,
  id_concepto integer NOT NULL UNIQUE REFERENCES "concepto de pago" (id_concepto) ON UPDATE CASCADE,
  id_ordinaria integer NOT NULL UNIQUE REFERENCES "cuota ordinaria" (id_ordinaria) ON UPDATE CASCADE,
  id_extraordinaria integer NOT NULL UNIQUE REFERENCES "cuota extraordinaria" (id_extraordinaria) ON UPDATE CASCADE,
  id_penalizacion integer NOT NULL UNIQUE REFERENCES "cuota de penalización" (id_penalizacion) ON UPDATE CASCADE,
  id_reserva integer NOT NULL UNIQUE REFERENCES "cuota de fondo de reserva" (id_reserva) ON UPDATE CASCADE,
  id_adeudos integer NOT NULL UNIQUE REFERENCES "adeudos anteriores" (id_adeudos) ON UPDATE CASCADE,
  id_total integer NOT NULL UNIQUE REFERENCES "total pagado" (id_total) ON UPDATE CASCADE,
  id_administrador integer NOT NULL REFERENCES administrador (id_administrador) ON UPDATE CASCADE,
  pdf_storage_key text,
  CONSTRAINT uq_recibo_condominio_numero UNIQUE (id_condominio, no_recibo),
  CONSTRAINT chk_recibo_numero_no_vacio CHECK (char_length(btrim(no_recibo)) > 0),
  CONSTRAINT chk_recibo_estado_pago CHECK (estado_pago IN ('pendiente', 'pagado')),
  CONSTRAINT chk_recibo_pago_fecha_estado CHECK (
    (estado_pago = 'pagado' AND fecha_pago IS NOT NULL)
    OR (estado_pago = 'pendiente' AND fecha_pago IS NULL)
  ),
  CONSTRAINT chk_recibo_fecha_pago_no_anticipada CHECK (
    fecha_pago IS NULL OR fecha_pago >= fecha::timestamp
  )
);

ALTER TABLE recibo ADD COLUMN IF NOT EXISTS pdf_storage_key text;

