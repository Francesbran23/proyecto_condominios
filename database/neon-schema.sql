CREATE INDEX IF NOT EXISTS id_condominio_idx_recibo ON recibo (id_condominio);
CREATE INDEX IF NOT EXISTS id_departamento_idx_recibo ON recibo (id_departamento);
CREATE INDEX IF NOT EXISTS id_inquilino_idx_recibo ON recibo (id_inquilino);
